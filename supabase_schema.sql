-- Ordem das colunas (por importância):
--   id | nome | telemovel | quando_ligar | quando_visitar | mensagem | origem | status | created_at
--
-- O script é seguro para correr mais do que uma vez e PRESERVA as leads
-- já existentes (migra-as da tabela antiga para a nova estrutura).
